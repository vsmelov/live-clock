package com.vsmelov.liveclock.domain

/**
 * ЕДИНСТВЕННОЕ МЕСТО, ГДЕ ЖИВУТ КОЭФФИЦИЕНТЫ. Правь здесь.
 *
 * Единица — минуты ожидаемой жизни. Минус укорачивает, плюс удлиняет.
 * Одна микрожизнь (Spiegelhalter) = 30 минут, см. [Microlives].
 *
 * Величины, выведенные из hazard ratio, посчитаны формулой из статьи, а не
 * подобраны на глаз: рядом с каждой видно исходный HR. Пруфы по каждому
 * действию лежат в [EventType] и показываются в приложении по кнопке «i».
 *
 * ВАЖНО ПРО ЕДИНИЦЫ. Почти вся эпидемиология здесь измеряет «за день
 * пожизненной привычки с 35 лет». То есть −30 за порцию мяса значит «есть
 * по порции каждый день десятилетиями», а не «съел стейк — минус полчаса».
 * Кнопка огрубляет это до разового события: жать удобно, но помни, чем платишь.
 *
 * Чтобы добавить тип: константа сюда + строка в [EventType] с [Evidence].
 * Поиск, закрепление, виджет и синк подхватят его сами.
 */
object Coefficients {

    /** Одна микрожизнь по Spiegelhalter — полчаса ожидаемой жизни. */
    const val MICROLIFE_MINUTES: Int = Microlives.MINUTES

    // ───────────────────────── Таблица BMJ 2012;345:e8223 ─────────────────────────
    // Значения взяты как опубликованы. Автор округляет до целых микрожизней,
    // поэтому они чуть грубее, чем дала бы формула: мясо по формуле −40, а
    // в таблице −30. Оставлены табличные — это числа самого автора.

    /** Сигарета: две сигареты = одна микрожизнь. */
    const val SMOKE: Int = -15

    /** Красное мясо, порция 85 г (3 унции) — одна микрожизнь. HR 1.13. */
    const val RED_MEAT: Int = -30

    /** Бургер — одна микрожизнь. Названа в тексте статьи отдельно от мяса. */
    const val FAST_FOOD: Int = -30

    /** Два часа у экрана = одна микрожизнь, значит полмикрожизни на час. HR 1.08. */
    const val TV: Int = -15

    /** Кофе: две-три чашки в день = одна микрожизнь, отсюда треть на чашку. HR 0.90. */
    const val COFFEE: Int = 10

    /**
     * Овощи и фрукты, одна порция.
     *
     * В таблице +4 микрожизни за ПЯТЬ И БОЛЕЕ порций в день, не за одну.
     * Поделено на пять: деление линейное, в источнике его нет, но для кнопки
     * «съел порцию» другого способа нет.
     */
    const val VEGETABLES: Int = 24

    /** Ходьба, километр. Из расширенной таблицы, +0.4 микрожизни. */
    const val WALK: Int = 12

    /** Сутки в сильно загрязнённом воздухе: Мехико против Лондона, −0.6 микрожизни. */
    const val AIR_POLLUTION: Int = -18

    // ──────────────── Посчитано формулой из отдельных исследований ────────────────
    // Microlives.minutesPerDay(HR) — та же формула, которой пользуется автор
    // таблицы. Исходный hazard ratio виден прямо в вызове.

    /** Заснул после двух ночи. UK Biobank, 433 268 человек, HR 1.10. */
    val LATE_NIGHT: Int = Microlives.minutesPerDay(hazardRatio = 1.10)

    /** Спал меньше семи часов. Мета-анализ, HR 1.14 против нормы 7–8 часов. */
    val SLEEP_SHORT: Int = Microlives.minutesPerDay(hazardRatio = 1.14)

    /**
     * Живое общение за день.
     *
     * Считано от социальной изоляции (OR 1.29), а не от контраста
     * «сильные против слабых связей» (OR 1.50): второй контраст крайний,
     * как «курильщик против никогда не курившего», и для одной кнопки
     * завышал бы.
     */
    val SOCIAL: Int = Microlives.minutesPerDay(hazardRatio = 1.0 / 1.29)

    /** Время среди зелени. Мета-анализ, HR 0.96 на +0.1 NDVI вокруг дома. */
    val NATURE: Int = Microlives.minutesPerDay(hazardRatio = 0.96)

    /** Сауна. Kuopio, 2315 мужчин, 20.7 года. 4–7 раз в неделю против одного, HR 0.60. */
    val SAUNA: Int = Microlives.minutesPerDay(hazardRatio = 0.60)

    /** Орехи, горсть в день. Гарвардские когорты, 7+ раз в неделю, HR 0.80. */
    val NUTS: Int = Microlives.minutesPerDay(hazardRatio = 0.80)

    /** Доехал на велосипеде вместо машины. UK Biobank, 263 450 человек, HR 0.59. */
    val BIKE_COMMUTE: Int = Microlives.minutesPerDay(hazardRatio = 0.59)

    /** Пробежка, хоть пять минут. 55 137 человек, 15 лет, HR 0.70. */
    val RUNNING: Int = Microlives.minutesPerDay(hazardRatio = 0.70)

    // ───────────────────────── Прикидки, а не исследования ─────────────────────────
    // Направление эффекта в литературе общепринято, но конкретной работы
    // под рукой нет. Величины назначены по порядку соседних строк, чтобы
    // приложение подталкивало в нужную сторону. Точности здесь не ищи.

    /** Рыба, порция. */
    const val FISH: Int = 20

    /** Сладкая газировка. */
    const val SUGARY_DRINK: Int = -20

    /** Сладкое: десерт, шоколадка, печенье. */
    const val SWEETS: Int = -10

    /** Тяжёлый стресс или конфликт за день. */
    const val STRESS: Int = -20

    /** Чтение: полчаса книги. */
    const val READING: Int = 15

    /** Зубная нить. */
    const val FLOSS: Int = 10

    /** Чай. */
    const val TEA: Int = 5

    /** Короткий дневной сон. */
    const val NAP: Int = 5

    /** Прививка от гриппа. */
    const val FLU_SHOT: Int = 15

    // ──────────────────────── Проверено, эффекта не нашли ────────────────────────
    // Ноль здесь — это результат, а не заглушка. Кнопка остаётся, чтобы
    // было видно: смотрели и не нашли.

    /** Мультивитамины. 390 124 человека, 20+ лет — выигрыша по смертности нет. */
    const val MULTIVITAMIN: Int = 0

    /**
     * Стакан воды.
     *
     * Громкое исследование про гидратацию мерило натрий в крови, а не
     * выпитую воду. Что «пить больше воды» продлевает жизнь — не показано.
     */
    const val WATER: Int = 0

    // ─────────────────────────── Оценка, а не источник ───────────────────────────

    /**
     * Секс.
     *
     * Прямой расчёт по Caerphilly даёт около +530 минут за раз — величина
     * заведомо неправдоподобная. Взята консервативная оценка на уровне
     * тренировки. Это моё решение, не число из работы.
     */
    const val SEX: Int = 60

    // ──────────────────────────── Слабый источник ────────────────────────────
    // Этих строк в статье BMJ нет — только в расширенной таблице
    // The Conversation, без ссылки на исследование.

    /** Кошка или собака: за день с питомцем — одна микрожизнь. */
    const val PET: Int = 30

    /** Умственная нагрузка за день — четыре микрожизни. */
    const val ACTIVE_MIND: Int = 120

    // ─────────────────────────── Выбрано тобой в ТЗ ───────────────────────────

    /**
     * Бокал алкоголя.
     *
     * В таблице первая доза за день даёт +1 микрожизнь, и только каждая
     * следующая до шести уходит в минус. Здесь плоский минус из ТЗ.
     * Поставь 30, если хочешь как в источнике.
     */
    const val DRINK: Int = -30

    /**
     * Тренировка от 20 минут.
     *
     * В таблице первые 20 минут стоят двух микрожизней (+60), следующие сорок
     * дают ещё от половины до одной. Здесь одна микрожизнь — как в ТЗ.
     * Поставь 60, если хочешь как в источнике.
     */
    const val WORKOUT: Int = 30

    /** Осознанный отдых или дыхательная практика. В источниках такого нет. */
    const val REST: Int = 15
}
