package com.vsmelov.liveclock.domain

/**
 * ЕДИНСТВЕННОЕ МЕСТО, ГДЕ ЖИВУТ КОЭФФИЦИЕНТЫ. Правь здесь.
 *
 * Модель — микрожизни (microlives, David Spiegelhalter): одна микрожизнь равна
 * [MICROLIFE_MINUTES] минутам ожидаемой продолжительности жизни, то есть
 * получасу. Значения ниже взяты из его таблицы и переведены в минуты.
 *
 * Источники:
 *   https://understandinguncertainty.org/microlives
 *   BMJ 2012;345:e8223
 *
 * Отрицательное значение укорачивает жизнь, положительное — удлиняет.
 *
 * Важно: событие запоминает дельту в момент записи (см. [LifeEvent.deltaMinutes]).
 * Правка коэффициента меняет только будущие события, уже записанный лог
 * не переписывается задним числом.
 *
 * Чтобы добавить новый тип события, нужно ровно два шага:
 *   1. добавить константу сюда;
 *   2. добавить строку в [EventType].
 * Поиск и сетка в Activity, закрепление и виджет подхватят новый тип сами.
 */
object Coefficients {

    /** Одна микрожизнь по Spiegelhalter — полчаса ожидаемой жизни. */
    const val MICROLIFE_MINUTES: Int = 30

    // --- Из таблицы BMJ 2012;345:e8223, Table 1 ---
    //
    // Важно про единицы. В статье таблица называется «изменение микрожизней
    // ПА ДЕНЬ ВОЗДЕЙСТВИЯ» для пожизненной привычки с 35 лет. То есть −1
    // микрожизнь за порцию мяса значит «есть по порции каждый день
    // десятилетиями», а не «съел стейк — минус полчаса». Кнопка в приложении
    // огрубляет это до разового события: удобно жать, но помни, чем платишь.

    /** Сигарета: две сигареты = одна микрожизнь, значит половина на штуку. */
    const val SMOKE: Int = -15

    /**
     * Красное мясо: порция = одна микрожизнь.
     *
     * Порция в статье определена жёстко — 85 г (3 унции), это меньше,
     * чем кажется: примерно одна котлета для бургера.
     * Источник величины — hazard ratio 1.13 из гарвардских когорт.
     */
    const val RED_MEAT: Int = -30

    /** Телевизор: два часа = одна микрожизнь, значит полмикрожизни на час. */
    const val TV: Int = -15

    /** Ходьба: километр = 0.4 микрожизни. */
    const val WALK: Int = 12

    /** Кофе: две-три чашки в день = одна микрожизнь, отсюда треть на чашку. */
    const val COFFEE: Int = 10

    /**
     * Овощи и фрукты, одна порция.
     *
     * В таблице стоит +4 микрожизни за ПЯТЬ И БОЛЕЕ порций в день, а не за
     * одну. Здесь величина поделена на пять — деление линейное и в источнике
     * его нет, но для кнопки «съел порцию» другого способа нет.
     *
     * Отдельно стоит знать, что эта строка самая шаткая во всей таблице:
     * hazard ratio 0.66 у мужчин, то есть минус треть смертности. Как
     * причинный эффект овощей это неправдоподобно много. Мерили не порции,
     * а витамин C в крови выше 50 нмоль/л — маркер, который заодно метит
     * тех, кто в целом лучше живёт, лучше спит и больше двигается.
     */
    const val VEGETABLES: Int = 24

    // --- В статье BMJ этого нет ---
    //
    // Эти две строки взяты из расширенной таблицы The Conversation, которая
    // ссылается на Spiegelhalter, но в самой статье таких строк нет и ссылки
    // на исследование при них не приведено. Доверия к ним меньше, чем
    // к остальным.

    /** Кошка или собака: за день с питомцем — одна микрожизнь. */
    const val PET: Int = 30

    /** Умственная нагрузка за день — четыре микрожизни. */
    const val ACTIVE_MIND: Int = 120

    // --- Отличается от таблицы. Значения выбраны тобой ---

    /**
     * Бокал алкоголя.
     *
     * В таблице Spiegelhalter первая доза за день оценивается как +1
     * микрожизнь, и только больше двух в день начинают укорачивать жизнь.
     * Здесь стоит плоская отрицательная величина из ТЗ — так проще жать
     * кнопку не задумываясь. Поставь 30, если хочешь как в источнике.
     */
    const val DRINK: Int = -30

    /**
     * Тренировка от 20 минут.
     *
     * В таблице первые 20 минут стоят двух микрожизней (+60 минут), а
     * следующие сорок дают ещё от половины до одной. Здесь одна микрожизнь —
     * как в ТЗ. Поставь 60, если хочешь как в источнике.
     */
    const val WORKOUT: Int = 30

    /** Осознанный отдых или дыхательная практика. В таблице такого нет. */
    const val REST: Int = 15
}
