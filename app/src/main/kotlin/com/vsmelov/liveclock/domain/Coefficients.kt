package com.vsmelov.liveclock.domain

/**
 * ЕДИНСТВЕННОЕ МЕСТО, ГДЕ ЖИВУТ КОЭФФИЦИЕНТЫ. Правь здесь.
 *
 * Модель — микрожизни (microlives, David Spiegelhalter): одна микрожизнь равна
 * [MICROLIFE_MINUTES] минутам ожидаемой продолжительности жизни, то есть
 * получасу. Значения ниже взяты из его таблицы и переведены в минуты.
 *
 * Источники:
 *   https://understandinguncertainty.org/microlives
 *   BMJ 2012;345:e8223
 *
 * Отрицательное значение укорачивает жизнь, положительное — удлиняет.
 *
 * Важно: событие запоминает дельту в момент записи (см. [LifeEvent.deltaMinutes]).
 * Правка коэффициента меняет только будущие события, уже записанный лог
 * не переписывается задним числом.
 *
 * Чтобы добавить новый тип события, нужно ровно два шага:
 *   1. добавить константу сюда;
 *   2. добавить строку в [EventType].
 * Поиск и сетка в Activity, закрепление и виджет подхватят новый тип сами.
 */
object Coefficients {

    /** Одна микрожизнь по Spiegelhalter — полчаса ожидаемой жизни. */
    const val MICROLIFE_MINUTES: Int = 30

    // --- Из таблицы один в один ---

    /** Сигарета: две сигареты = одна микрожизнь, значит половина на штуку. */
    const val SMOKE: Int = -15

    /** Красное мясо: порция = одна микрожизнь. */
    const val RED_MEAT: Int = -30

    /** Телевизор: час = половина микрожизни. */
    const val TV: Int = -15

    /** Ходьба: километр = 0.4 микрожизни. */
    const val WALK: Int = 12

    /** Кофе: чашка = 0.3 микрожизни. Две-три чашки в день дают полчаса. */
    const val COFFEE: Int = 10

    /** Кошка или собака: за день с питомцем — одна микрожизнь. */
    const val PET: Int = 30

    /**
     * Овощи: порция = четыре микрожизни.
     *
     * Величина выглядит несоразмерно большой рядом с сигаретой, но она
     * из таблицы. Если перекос мешает — правь здесь.
     */
    const val VEGETABLES: Int = 120

    /** Умственная нагрузка за день — четыре микрожизни. */
    const val ACTIVE_MIND: Int = 120

    // --- Отличается от таблицы. Значения выбраны тобой ---

    /**
     * Бокал алкоголя.
     *
     * В таблице Spiegelhalter первая доза за день оценивается как +1
     * микрожизнь, и только больше двух в день начинают укорачивать жизнь.
     * Здесь стоит плоская отрицательная величина из ТЗ — так проще жать
     * кнопку не задумываясь. Поставь 30, если хочешь как в источнике.
     */
    const val DRINK: Int = -30

    /**
     * Тренировка от 20 минут.
     *
     * В таблице первые 20 минут стоят двух микрожизней (+60 минут), каждые
     * следующие двадцать дают меньше. Здесь одна микрожизнь — как в ТЗ.
     */
    const val WORKOUT: Int = 30

    /** Осознанный отдых или дыхательная практика. В таблице такого нет. */
    const val REST: Int = 15
}
