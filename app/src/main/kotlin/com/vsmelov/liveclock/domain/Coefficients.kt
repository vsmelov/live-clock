package com.vsmelov.liveclock.domain

/**
 * ЕДИНСТВЕННОЕ МЕСТО, ГДЕ ЖИВУТ КОЭФФИЦИЕНТЫ. Правь здесь.
 *
 * Модель — микрожизни (microlives, David Spiegelhalter): одна микрожизнь равна
 * [MICROLIFE_MINUTES] минутам ожидаемой продолжительности жизни, то есть
 * получасу. Значения ниже — это калибровка в микрожизнях, переведённая в минуты:
 * две сигареты стоят примерно одну микрожизнь, двадцать минут нагрузки
 * примерно одну возвращают.
 *
 * Отрицательное значение укорачивает жизнь, положительное — удлиняет.
 *
 * Важно: событие запоминает дельту в момент записи (см. [LifeEvent.deltaMinutes]).
 * Правка коэффициента меняет только будущие события, уже записанный лог
 * не переписывается задним числом.
 *
 * Чтобы добавить новый тип события, нужно ровно два шага:
 *   1. добавить константу сюда;
 *   2. добавить строку в [EventType].
 * Виджет, сетка в Activity и синк подхватят новый тип сами.
 */
object Coefficients {

    /** Одна микрожизнь по Spiegelhalter — полчаса ожидаемой жизни. */
    const val MICROLIFE_MINUTES: Int = 30

    /** Сигарета: две сигареты ≈ одна микрожизнь, значит половина на штуку. */
    const val SMOKE: Int = -15

    /**
     * Бокал алкоголя — одна микрожизнь.
     *
     * В исходной таблице Spiegelhalter алкоголь нелинеен: первая доза за день
     * оценивается мягче последующих. Здесь сознательно взята одна плоская
     * величина из ТЗ — так проще жать кнопку не задумываясь. Если захочешь
     * нелинейность, это место для правки.
     */
    const val DRINK: Int = -30

    /** Осознанный отдых или дыхательная практика. */
    const val REST: Int = 15

    /** Тренировка от 20 минут ≈ одна микрожизнь. */
    const val WORKOUT: Int = 30
}
